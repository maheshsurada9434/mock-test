// INITIALIZE
// ============================================================
async function init() {
    if (!checkElements()) {
        alert(
            'Test page error: Some required HTML elements are missing. Check test.html IDs.'
        );
        return;
    }
    try {
        // ----------------------------------------------------
        // GET TOKEN
        // ----------------------------------------------------
        const token =
            tokenFromUrl();
        rawToken = token || '';
        // ----------------------------------------------------
        // NO TOKEN
        // ----------------------------------------------------
        if (!token) {
            loadMsg.textContent =
                'This page needs a test link generated by the teacher.';
            return;
        }
        // ----------------------------------------------------
        // DECODE TEST (handles both plain and gzip links)
        // ----------------------------------------------------
        test =
            await decodeTestAsync(token);
        // ----------------------------------------------------
        // INVALID TEST
        // ----------------------------------------------------
        if (
            !test ||
            !Array.isArray(
                test.questions
            ) ||
            test.questions.length === 0
        ) {
            loadMsg.textContent =
                'The test link is invalid or contains no questions.';
            return;
        }
        // ----------------------------------------------------
        // DEFAULT TITLE
        // ----------------------------------------------------
        if (
            !test.title ||
            String(test.title).trim() === ''
        ) {
            test.title =
                'Mock Test';
        }
        // ----------------------------------------------------
        // VALIDATE MINUTES
        // ----------------------------------------------------
        test.minutes =
            Math.max(
                1,
                Number(
                    test.minutes
                ) || 30
            );
        // ----------------------------------------------------
        // SHOW START SCREEN
        // ----------------------------------------------------
        loading.classList.add(
            'hidden'
        );
        start.classList.remove(
            'hidden'
        );
        // ----------------------------------------------------
        // TEST INFORMATION
        // ----------------------------------------------------
        testTitle.textContent =
            test.title;
        startTitle.textContent =
            test.title;
        testInfo.textContent =
            test.questions.length +
            ' questions • ' +
            test.minutes +
            ' minutes' +
            (
                test.negativeMarking
                    ? ' • -' +
                      test.negativeMarking +
                      ' per wrong answer'
                    : ''
            );
        // ----------------------------------------------------
        // CHECK FOR A RESUMABLE ATTEMPT
        // ----------------------------------------------------
        progressKey =
            'mockProgress:' +
            hashToken(rawToken);
        offerResumeIfAvailable();
    } catch (error) {
        console.error(
            'Test loading error:',
            error
        );
        loadMsg.textContent =
            'Unable to load the test: ' +
            (
                error.message ||
                String(error)
            );
    }
}
// ============================================================
// RESUME-IN-PROGRESS SUPPORT (sessionStorage only — survives a
// refresh or accidental tab close/reopen in the same tab, but
// not a switch to a different device or browser)
// ============================================================
function saveProgress() {
    try {
        sessionStorage.setItem(
            progressKey,
            JSON.stringify({
                order:
                    questions.map(
                        function (q) {
                            return q.id;
                        }
                    ),
                idx: idx,
                answers: answers,
                marked: marked,
                seconds: seconds,
                studentName: studentName,
                rollNo: rollNo
            })
        );
    } catch (error) {
        // sessionStorage may be unavailable (e.g. private mode) —
        // resuming is a nicety, not a requirement, so fail quietly
        console.error('Progress save error:', error);
    }
}
function clearProgress() {
    try {
        sessionStorage.removeItem(
            progressKey
        );
    } catch (error) {
        // ignore
    }
}
function loadProgress() {
    try {
        const raw =
            sessionStorage.getItem(
                progressKey
            );
        if (!raw) {
            return null;
        }
        const saved =
            JSON.parse(raw);
        if (
            !saved ||
            !Array.isArray(saved.order) ||
            saved.order.length !== test.questions.length
        ) {
            return null;
        }
        return saved;
    } catch (error) {
        return null;
    }
}
function offerResumeIfAvailable() {
    const saved =
        loadProgress();
    if (!saved) {
        resumeBanner.classList.add(
            'hidden'
        );
        return;
    }
    const answeredN =
        Object.keys(
            saved.answers || {}
        ).length;
    resumeInfo.textContent =
        (
            saved.studentName ||
            'Unnamed attempt'
        ) +
        ' • Question ' +
        (saved.idx + 1) +
        ' of ' +
        saved.order.length +
        ' • ' +
        answeredN +
        ' answered • ' +
        fmt(saved.seconds) +
        ' remaining';
    resumeBanner.classList.remove(
        'hidden'
    );
    resumeBtn.onclick =
        function () {
            resumeAttempt(saved);
        };
    freshBtn.onclick =
        function () {
            clearProgress();
            resumeBanner.classList.add(
                'hidden'
            );
        };
}
function resumeAttempt(saved) {
    const byId = {};
    test.questions.forEach(
        function (q) {
            byId[q.id] = q;
        }
    );
    questions =
        saved.order
            .map(function (id) {
                return byId[id];
            })
            .filter(Boolean);
    if (questions.length !== saved.order.length) {
        alert(
            'Unable to restore that attempt. Starting fresh instead.'
        );
        clearProgress();
        return;
    }
    idx = saved.idx || 0;
    answers = saved.answers || {};
    marked = saved.marked || {};
    seconds = Math.max(
        0,
        Number(saved.seconds) || 0
    );
    studentName =
        saved.studentName || '';
    rollNo =
        saved.rollNo || '';
    finished = false;
    startTime =
        Date.now() -
        (test.minutes * 60 - seconds) * 1000;
    numbers.dataset.built = '';
    clearInterval(timerId);
    timer.classList.remove('urgent');
    start.classList.add('hidden');
    exam.classList.remove('hidden');
    render();
    updateTimer();
    timerId =
        setInterval(tick, 1000);
}
