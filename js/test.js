import {
    decodeTest,
    tokenFromUrl,
    esc,
    fmt
} from './common.js';
// ============================================================
// VARIABLES
// ============================================================
let test = null;
let idx = 0;
let answers = {};
let seconds = 0;
let timerId = null;
let startTime = 0;
let studentName = '';
let rollNo = '';
// ============================================================
// INITIALIZE
// ============================================================
function init() {
    try {
        const token =
            tokenFromUrl();
        // ----------------------------------------------------
        // No token
        // ----------------------------------------------------
        if (!token) {
            loadMsg.textContent =
                'This page needs a test link generated by the teacher.';
            return;
        }
        // ----------------------------------------------------
        // IMPORTANT:
        // decodeTest() is now SYNCHRONOUS
        // Do NOT use await here.
        // ----------------------------------------------------
        test =
            decodeTest(token);
        // ----------------------------------------------------
        // Invalid test
        // ----------------------------------------------------
        if (
            !test ||
            !Array.isArray(test.questions) ||
            test.questions.length === 0
        ) {
            loadMsg.textContent =
                'The test link is invalid or contains no questions.';
            return;
        }
        // ----------------------------------------------------
        // Make sure minutes is valid
        // ----------------------------------------------------
        test.minutes =
            Math.max(
                1,
                Number(test.minutes) || 30
            );
        // ----------------------------------------------------
        // Hide loading
        // Show start screen
        // ----------------------------------------------------
        loading.classList.add(
            'hidden'
        );
        start.classList.remove(
            'hidden'
        );
        // ----------------------------------------------------
        // Test information
        // ----------------------------------------------------
        testTitle.textContent =
            test.title ||
            'Mock Test';
        startTitle.textContent =
            test.title ||
            'Mock Test';
        testInfo.textContent =
            test.questions.length +
            ' questions • ' +
            test.minutes +
            ' minutes';
    } catch (error) {
        console.error(
            'Test loading error:',
            error
        );
        loadMsg.textContent =
            'Unable to load the test: ' +
            (error.message ||
            String(error));
    }
}
// ============================================================
// START TEST
// ============================================================
startBtn.onclick =
    begin;
// ============================================================
// BEGIN
// ============================================================
function begin() {
    studentName =
        document
            .getElementById(
                'studentName'
            )
            .value
            .trim();
    rollNo =
        document
            .getElementById(
                'rollNo'
            )
            .value
            .trim();
    // --------------------------------------------------------
    // Student name required
    // --------------------------------------------------------
    if (!studentName) {
        alert(
            'Please enter your name.'
        );
        document
            .getElementById(
                'studentName'
            )
            .focus();
        return;
    }
    // --------------------------------------------------------
    // Reset
    // --------------------------------------------------------
    idx = 0;
    answers = {};
    seconds =
        test.minutes * 60;
    startTime =
        Date.now();
    // --------------------------------------------------------
    // Show exam
    // --------------------------------------------------------
    start.classList.add(
        'hidden'
    );
    exam.classList.remove(
        'hidden'
    );
    // --------------------------------------------------------
    // Render first question
    // --------------------------------------------------------
    render();
    // --------------------------------------------------------
    // Start timer
    // --------------------------------------------------------
    clearInterval(
        timerId
    );
    timerId =
        setInterval(
            tick,
            1000
        );
    tick();
}
// ============================================================
// TIMER
// ============================================================
function tick() {
    seconds--;
    if (seconds < 0) {
        seconds = 0;
    }
    timer.textContent =
        fmt(seconds);
    // --------------------------------------------------------
    // Last 60 seconds
    // --------------------------------------------------------
    if (seconds <= 60) {
        timer.classList.add(
            'urgent'
        );
    }
    // --------------------------------------------------------
    // Time finished
    // --------------------------------------------------------
    if (seconds <= 0) {
        clearInterval(
            timerId
        );
        finish(true);
    }
}
// ============================================================
// RENDER QUESTION
// ============================================================
function render() {
    const q =
        test.questions[idx];
    if (!q) {
        return;
    }
    // --------------------------------------------------------
    // Progress
    // --------------------------------------------------------
    progress.textContent =
        'Question ' +
        (idx + 1) +
        ' of ' +
        test.questions.length;
    // --------------------------------------------------------
    // Answered count
    // --------------------------------------------------------
    answeredCount.textContent =
        Object.keys(
            answers
        ).length +
        ' answered';
    // --------------------------------------------------------
    // Question
    // --------------------------------------------------------
    question.innerHTML =
        '<h2>' +
        esc(q.question) +
        '</h2>' +
        Object.entries(
            q.options || {}
        )
        .map(
            function ([key, value]) {
                const selected =
                    answers[q.id] === key
                        ? ' selected'
                        : '';
                return (
                    '<button ' +
                    'type="button" ' +
                    'class="option' +
                    selected +
                    '" ' +
                    'data-option="' +
                    esc(key) +
                    '">' +
                    '<b>' +
                    esc(key) +
                    ')</b> ' +
                    esc(value) +
                    '</button>'
                );
            }
        )
        .join('');
    // --------------------------------------------------------
    // Option buttons
    // --------------------------------------------------------
    question
        .querySelectorAll(
            '.option'
        )
        .forEach(
            function (button) {
                button.onclick =
                    function () {
                        answers[q.id] =
                            button.dataset.option;
                        render();
                    };
            }
        );
    // --------------------------------------------------------
    // Previous
    // --------------------------------------------------------
    prevBtn.disabled =
        idx === 0;
    // --------------------------------------------------------
    // Next
    // --------------------------------------------------------
    nextBtn.disabled =
        idx ===
        test.questions.length - 1;
    // --------------------------------------------------------
    // Question numbers
    // --------------------------------------------------------
    numbers.innerHTML =
        test.questions
            .map(
                function (item, n) {
                    return (
                        '<button ' +
                        'type="button" ' +
                        'class="qnum ' +
                        (
                            answers[item.id]
                                ? 'answered '
                                : ''
                        ) +
                        (
                            n === idx
                                ? 'current'
                                : ''
                        ) +
                        '">' +
                        (n + 1) +
                        '</button>'
                    );
                }
            )
            .join('');
    // --------------------------------------------------------
    // Question number navigation
    // --------------------------------------------------------
    numbers
        .querySelectorAll(
            '.qnum'
        )
        .forEach(
            function (button, n) {
                button.onclick =
                    function () {
                        idx = n;
                        render();
                    };
            }
        );
}
// ============================================================
// PREVIOUS BUTTON
// ============================================================
prevBtn.onclick =
    function () {
        if (idx > 0) {
            idx--;
            render();
        }
    };
// ============================================================
// NEXT BUTTON
// ============================================================
nextBtn.onclick =
    function () {
        if (
            idx <
            test.questions.length - 1
        ) {
            idx++;
            render();
        }
    };
// ============================================================
// SUBMIT BUTTON
// ============================================================
submitBtn.onclick =
    function () {
        finish(false);
    };
// ============================================================
// FINISH TEST
// ============================================================
function finish(auto) {
    // --------------------------------------------------------
    // Prevent invalid state
    // --------------------------------------------------------
    if (
        !test ||
        !test.questions
    ) {
        return;
    }
    // --------------------------------------------------------
    // Manual submit confirmation
    // --------------------------------------------------------
    if (!auto) {
        if (
            !confirm(
                'Are you sure you want to submit the test?'
            )
        ) {
            return;
        }
    }
    // --------------------------------------------------------
    // Stop timer
    // --------------------------------------------------------
    clearInterval(
        timerId
    );
    // --------------------------------------------------------
    // Calculate correct answers
    // --------------------------------------------------------
    let correct = 0;
    test.questions.forEach(
        function (q) {
            if (
                answers[q.id] ===
                q.answer
            ) {
                correct++;
            }
        }
    );
    // --------------------------------------------------------
    // Attempted
    // --------------------------------------------------------
    const attempted =
        Object.keys(
            answers
        ).length;
    // --------------------------------------------------------
    // Wrong
    // --------------------------------------------------------
    let wrong = 0;
    Object.keys(
        answers
    ).forEach(
        function (id) {
            const q =
                test.questions.find(
                    function (item) {
                        return (
                            String(item.id) ===
                            String(id)
                        );
                    }
                );
            if (
                q &&
                answers[id] !==
                q.answer
            ) {
                wrong++;
            }
        }
    );
    // --------------------------------------------------------
    // Unanswered
    // --------------------------------------------------------
    const unanswered =
        test.questions.length -
        attempted;
    // --------------------------------------------------------
    // Percentage
    // --------------------------------------------------------
    const percent =
        test.questions.length > 0
            ? Math.round(
                (
                    correct /
                    test.questions.length
                ) * 100
            )
            : 0;
    // --------------------------------------------------------
    // Time taken
    // --------------------------------------------------------
    const timeTaken =
        Math.round(
            (
                Date.now() -
                startTime
            ) / 1000
        );
    // --------------------------------------------------------
    // Result
    // --------------------------------------------------------
    const result = {
        title:
            test.title,
        name:
            studentName,
        roll:
            rollNo,
        total:
            test.questions.length,
        attempted:
            attempted,
        correct:
            correct,
        wrong:
            wrong,
        unanswered:
            unanswered,
        percent:
            percent,
        timeTaken:
            timeTaken,
        answers:
            answers,
        questions:
            test.questions,
        autoSubmitted:
            auto
    };
    // --------------------------------------------------------
    // Save result
    // --------------------------------------------------------
    try {
        sessionStorage.setItem(
            'mockResult',
            JSON.stringify(
                result
            )
        );
    } catch (error) {
        console.error(
            'Result save error:',
            error
        );
        alert(
            'Unable to save your result.'
        );
        return;
    }
    // --------------------------------------------------------
    // Go to result page
    // --------------------------------------------------------
    window.location.href =
        'result.html';
}
// ============================================================
// INITIALIZE
// ============================================================
init();
