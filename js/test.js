import {
    decodeTest,
    tokenFromUrl,
    esc,
    fmt
} from './common.js';
// ============================================================
// VARIABLES
// ============================================================
let test = null;
let idx = 0;
let answers = {};
let seconds = 0;
let timerId = null;
let startTime = 0;
let studentName = '';
let rollNo = '';
// ============================================================
// DOM ELEMENTS
// ============================================================
const loading =
    document.getElementById('loading');
const loadMsg =
    document.getElementById('loadMsg');
const start =
    document.getElementById('start');
const exam =
    document.getElementById('exam');
const startBtn =
    document.getElementById('startBtn');
const studentNameInput =
    document.getElementById('studentName');
const rollNoInput =
    document.getElementById('rollNo');
const testTitle =
    document.getElementById('testTitle');
const startTitle =
    document.getElementById('startTitle');
const testInfo =
    document.getElementById('testInfo');
const progress =
    document.getElementById('progress');
const answeredCount =
    document.getElementById('answeredCount');
const question =
    document.getElementById('question');
const numbers =
    document.getElementById('numbers');
const timer =
    document.getElementById('timer');
const prevBtn =
    document.getElementById('prevBtn');
const nextBtn =
    document.getElementById('nextBtn');
const submitBtn =
    document.getElementById('submitBtn');
// ============================================================
// INITIALIZE TEST
// ============================================================
function init() {
    try {
        // ----------------------------------------------------
        // Get token from URL
        // ----------------------------------------------------
        const token =
            tokenFromUrl();
        if (!token) {
            showLoadError(
                'This page needs a test link generated by the teacher.'
            );
            return;
        }
        // ----------------------------------------------------
        // Decode test
        //
        // New "u" links are synchronous.
        // ----------------------------------------------------
        test =
            decodeTest(token);
        // ----------------------------------------------------
        // Validate test
        // ----------------------------------------------------
        if (
            !test ||
            !Array.isArray(test.questions) ||
            test.questions.length === 0
        ) {
            showLoadError(
                'The test link is invalid or the test contains no questions.'
            );
            return;
        }
        // ----------------------------------------------------
        // Validate test duration
        // ----------------------------------------------------
        const minutes =
            Math.max(
                1,
                Number(test.minutes) || 30
            );
        test.minutes = minutes;
        // ----------------------------------------------------
        // Display test information
        // ----------------------------------------------------
        testTitle.textContent =
            test.title || 'Mock Test';
        startTitle.textContent =
            test.title || 'Mock Test';
        testInfo.textContent =
            test.questions.length +
            ' questions • ' +
            test.minutes +
            ' minutes';
        // ----------------------------------------------------
        // Hide loading
        // Show start screen
        // ----------------------------------------------------
        if (loading) {
            loading.classList.add('hidden');
        }
        if (start) {
            start.classList.remove('hidden');
        }
    } catch (error) {
        console.error(
            'Test initialization error:',
            error
        );
        showLoadError(
            'Unable to load the test. ' +
            (error.message || String(error))
        );
    }
}
// ============================================================
// SHOW LOADING ERROR
// ============================================================
function showLoadError(message) {
    if (loadMsg) {
        loadMsg.textContent = message;
    }
    if (loading) {
        loading.classList.remove('hidden');
    }
    if (start) {
        start.classList.add('hidden');
    }
    if (exam) {
        exam.classList.add('hidden');
    }
}
// ============================================================
// START BUTTON
// ============================================================
if (startBtn) {
    startBtn.onclick = begin;
}
// ============================================================
// BEGIN TEST
// ============================================================
function begin() {
    studentName =
        studentNameInput
            ? studentNameInput.value.trim()
            : '';
    rollNo =
        rollNoInput
            ? rollNoInput.value.trim()
            : '';
    // --------------------------------------------------------
    // Student name required
    // --------------------------------------------------------
    if (!studentName) {
        alert(
            'Please enter your name.'
        );
        if (studentNameInput) {
            studentNameInput.focus();
        }
        return;
    }
    // --------------------------------------------------------
    // Reset test state
    // --------------------------------------------------------
    idx = 0;
    answers = {};
    seconds =
        Math.max(
            1,
            Number(test.minutes) || 30
        ) * 60;
    startTime =
        Date.now();
    // --------------------------------------------------------
    // Show exam
    // --------------------------------------------------------
    if (start) {
        start.classList.add('hidden');
    }
    if (exam) {
        exam.classList.remove('hidden');
    }
    // --------------------------------------------------------
    // Render first question
    // --------------------------------------------------------
    render();
    // --------------------------------------------------------
    // Start timer
    // --------------------------------------------------------
    clearInterval(timerId);
    timerId =
        setInterval(
            tick,
            1000
        );
    tick();
}
// ============================================================
// TIMER
// ============================================================
function tick() {
    seconds--;
    if (seconds < 0) {
        seconds = 0;
    }
    if (timer) {
        timer.textContent =
            fmt(seconds);
        if (seconds <= 60) {
            timer.classList.add(
                'urgent'
            );
        }
    }
    // --------------------------------------------------------
    // Time finished
    // --------------------------------------------------------
    if (seconds <= 0) {
        clearInterval(
            timerId
        );
        finish(true);
    }
}
// ============================================================
// RENDER QUESTION
// ============================================================
function render() {
    if (
        !test ||
        !test.questions ||
        !test.questions.length
    ) {
        return;
    }
    const q =
        test.questions[idx];
    if (!q) {
        return;
    }
    // --------------------------------------------------------
    // Progress
    // --------------------------------------------------------
    if (progress) {
        progress.textContent =
            'Question ' +
            (idx + 1) +
            ' of ' +
            test.questions.length;
    }
    // --------------------------------------------------------
    // Answered count
    // --------------------------------------------------------
    if (answeredCount) {
        answeredCount.textContent =
            Object.keys(answers).length +
            ' answered';
    }
    // --------------------------------------------------------
    // Question + options
    // --------------------------------------------------------
    if (question) {
        const options =
            Object.entries(
                q.options || {}
            )
            .map(
                function ([key, value]) {
                    const selected =
                        answers[q.id] === key
                            ? ' selected'
                            : '';
                    return (
                        '<button ' +
                        'type="button" ' +
                        'class="option' +
                        selected +
                        '" ' +
                        'data-option="' +
                        esc(key) +
                        '">' +
                        '<b>' +
                        esc(key) +
                        ')</b> ' +
                        esc(value) +
                        '</button>'
                    );
                }
            )
            .join('');
        question.innerHTML =
            '<h2>' +
            esc(q.question) +
            '</h2>' +
            options;
        // ----------------------------------------------------
        // Option click
        // ----------------------------------------------------
        question
            .querySelectorAll(
                '.option'
            )
            .forEach(
                function (button) {
                    button.onclick =
                        function () {
                            const selected =
                                button.dataset.option;
                            answers[q.id] =
                                selected;
                            render();
                        };
                }
            );
    }
    // --------------------------------------------------------
    // Previous button
    // --------------------------------------------------------
    if (prevBtn) {
        prevBtn.disabled =
            idx === 0;
    }
    // --------------------------------------------------------
    // Next button
    // --------------------------------------------------------
    if (nextBtn) {
        nextBtn.disabled =
            idx ===
            test.questions.length - 1;
    }
    // --------------------------------------------------------
    // Question number buttons
    // --------------------------------------------------------
    if (numbers) {
        numbers.innerHTML =
            test.questions
                .map(
                    function (item, n) {
                        const answered =
                            answers[item.id]
                                ? ' answered'
                                : '';
                        const current =
                            n === idx
                                ? ' current'
                                : '';
                        return (
                            '<button ' +
                            'type="button" ' +
                            'class="qnum' +
                            answered +
                            current +
                            '">' +
                            (n + 1) +
                            '</button>'
                        );
                    }
                )
                .join('');
        numbers
            .querySelectorAll(
                '.qnum'
            )
            .forEach(
                function (button, n) {
                    button.onclick =
                        function () {
                            idx = n;
                            render();
                        };
                }
            );
    }
}
// ============================================================
// PREVIOUS BUTTON
// ============================================================
if (prevBtn) {
    prevBtn.onclick =
        function () {
            if (idx > 0) {
                idx--;
                render();
            }
        };
}
// ============================================================
// NEXT BUTTON
// ============================================================
if (nextBtn) {
    nextBtn.onclick =
        function () {
            if (
                idx <
                test.questions.length - 1
            ) {
                idx++;
                render();
            }
        };
}
// ============================================================
// SUBMIT BUTTON
// ============================================================
if (submitBtn) {
    submitBtn.onclick =
        function () {
            finish(false);
        };
}
// ============================================================
// FINISH TEST
// ============================================================
function finish(auto) {
    // --------------------------------------------------------
    // Prevent duplicate submission
    // --------------------------------------------------------
    if (
        !test ||
        !test.questions
    ) {
        return;
    }
    // --------------------------------------------------------
    // Manual confirmation
    // --------------------------------------------------------
    if (!auto) {
        const confirmed =
            confirm(
                'Are you sure you want to submit the test?'
            );
        if (!confirmed) {
            return;
        }
    }
    // --------------------------------------------------------
    // Stop timer
    // --------------------------------------------------------
    clearInterval(
        timerId
    );
    // --------------------------------------------------------
    // Calculate result
    // --------------------------------------------------------
    let correct = 0;
    test.questions.forEach(
        function (q) {
            if (
                answers[q.id] ===
                q.answer
            ) {
                correct++;
            }
        }
    );
    const attempted =
        Object.keys(
            answers
        ).length;
    let wrong = 0;
    Object.keys(
        answers
    ).forEach(
        function (id) {
            const q =
                test.questions.find(
                    function (item) {
                        return (
                            String(item.id) ===
                            String(id)
                        );
                    }
                );
            if (
                q &&
                answers[id] !==
                q.answer
            ) {
                wrong++;
            }
        }
    );
    const total =
        test.questions.length;
    const unanswered =
        Math.max(
            0,
            total - attempted
        );
    const percent =
        total > 0
            ? Math.round(
                (correct / total) *
                100
            )
            : 0;
    const timeTaken =
        Math.max(
            0,
            Math.round(
                (Date.now() -
                    startTime) /
                1000
            )
        );
    // --------------------------------------------------------
    // Result object
    // --------------------------------------------------------
    const result = {
        title:
            test.title ||
            'Mock Test',
        name:
            studentName,
        roll:
            rollNo,
        total:
            total,
        attempted:
            attempted,
        correct:
            correct,
        wrong:
            wrong,
        unanswered:
            unanswered,
        percent:
            percent,
        timeTaken:
            timeTaken,
        answers:
            answers,
        questions:
            test.questions,
        autoSubmitted:
            auto
    };
    // --------------------------------------------------------
    // Save result
    // --------------------------------------------------------
    try {
        sessionStorage.setItem(
            'mockResult',
            JSON.stringify(result)
        );
    } catch (error) {
        console.error(
            'Unable to save result:',
            error
        );
        alert(
            'Unable to save the test result in this browser.'
        );
        return;
    }
    // --------------------------------------------------------
    // Open result page
    // --------------------------------------------------------
    window.location.href =
        'result.html';
}
// ============================================================
// START
// ============================================================
init();
