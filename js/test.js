// CHECK REQUIRED HTML ELEMENTS
// ============================================================
function checkElements() {
    const required = {
        loadMsg,
        loading,
        start,
        exam,
        testTitle,
        startTitle,
        testInfo,
        resumeBanner,
        resumeInfo,
        resumeBtn,
        freshBtn,
        startBtn,
        timer,
        progress,
        answeredCount,
        question,
        prevBtn,
        nextBtn,
        markBtn,
        submitBtn,
        numbers
    };
    const missing =
        Object.keys(required)
            .filter(
                key => !required[key]
            );
    if (missing.length > 0) {
        console.error(
            'Missing HTML elements:',
            missing
        );
        return false;
    }
    return true;
}
// ============================================================
// SHUFFLE (Fisher-Yates)
// ============================================================
function shuffleArray(arr) {
    for (let i = arr.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [arr[i], arr[j]] = [arr[j], arr[i]];
    }
    return arr;
}
