import {decodeTest,tokenFromUrl,esc,fmt} from './common.js';
let test,idx=0,answers={},seconds=0,timerId,startTime=0,studentName='',rollNo='';
async function init(){
 const token=tokenFromUrl();
 if(!token){loadMsg.textContent='This page needs a test link generated by the teacher.';return}
 test=await decodeTest(token);
 if(!test){loadMsg.textContent='The test link is invalid or the browser cannot decode it.';return}
 loading.classList.add('hidden');start.classList.remove('hidden');testTitle.textContent=test.title;startTitle.textContent=test.title;testInfo.textContent=test.questions.length+' questions • '+test.minutes+' minutes';
}
startBtn.onclick=begin;
function begin(){
 studentName=document.getElementById('studentName').value.trim();rollNo=document.getElementById('rollNo').value.trim();
 if(!studentName)return alert('Please enter your name.');
 start.classList.add('hidden');exam.classList.remove('hidden');seconds=test.minutes*60;startTime=Date.now();render();timerId=setInterval(tick,1000);tick();
}
function tick(){seconds--;timer.textContent=fmt(seconds);if(seconds<=60)timer.classList.add('urgent');if(seconds<=0){clearInterval(timerId);finish(true)}}
function render(){
 const q=test.questions[idx];progress.textContent='Question '+(idx+1)+' of '+test.questions.length;answeredCount.textContent=Object.keys(answers).length+' answered';
 question.innerHTML='<h2>'+esc(q.question)+'</h2>'+Object.entries(q.options).map(([k,v])=>'<button class="option '+(answers[q.id]===k?'selected':'')+'" data-option="'+k+'">'+k+') '+esc(v)+'</button>').join('');
 question.querySelectorAll('.option').forEach(b=>b.onclick=()=>{answers[q.id]=b.dataset.option;render()});
 prevBtn.disabled=idx===0;nextBtn.disabled=idx===test.questions.length-1;
 numbers.innerHTML=test.questions.map((q,n)=>'<button class="qnum '+(answers[q.id]?'answered':'')+' '+(n===idx?'current':'')+'">'+(n+1)+'</button>').join('');
 numbers.querySelectorAll('.qnum').forEach((b,n)=>b.onclick=()=>{idx=n;render()});
}
prevBtn.onclick=()=>{if(idx>0){idx--;render()}};nextBtn.onclick=()=>{if(idx<test.questions.length-1){idx++;render()}};submitBtn.onclick=()=>finish(false);
function finish(auto){
 if(!auto&&!confirm('Are you sure you want to submit the test?'))return;
 clearInterval(timerId);
 let correct=0;test.questions.forEach(q=>{if(answers[q.id]===q.answer)correct++});
 const attempted=Object.keys(answers).length,wrong=Object.keys(answers).filter(id=>{const q=test.questions.find(x=>String(x.id)===String(id));return q&&answers[id]!==q.answer}).length;
 const result={title:test.title,name:studentName,roll:rollNo,total:test.questions.length,attempted,correct,wrong,unanswered:test.questions.length-attempted,percent:Math.round(correct/test.questions.length*100),timeTaken:Math.round((Date.now()-startTime)/1000),answers,questions:test.questions,autoSubmitted:auto};
 sessionStorage.setItem('mockResult',JSON.stringify(result));location.href='result.html';
}
init();