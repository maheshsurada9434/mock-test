// BEGIN TEST
// ============================================================
function begin() {
    const nameInput =
        document.getElementById(
            'studentName'
        );
    const rollInput =
        document.getElementById(
            'rollNo'
        );
    studentName =
        nameInput
            ? nameInput.value.trim()
            : '';
    rollNo =
        rollInput
            ? rollInput.value.trim()
            : '';
    // --------------------------------------------------------
    // NAME REQUIRED
    // --------------------------------------------------------
    if (!studentName) {
        alert(
            'Please enter your name.'
        );
        if (nameInput) {
            nameInput.focus();
        }
        return;
    }
    // --------------------------------------------------------
    // RESET
    // --------------------------------------------------------
    idx = 0;
    answers = {};
    marked = {};
    finished = false;
    seconds =
        test.minutes * 60;
    startTime =
        Date.now();
    // --------------------------------------------------------
    // QUESTION ORDER (shuffled per attempt if the teacher
    // enabled it — option order within a question is shuffled
    // separately at render time)
    // --------------------------------------------------------
    questions =
        test.shuffle
            ? shuffleArray(
                  test.questions.slice()
              )
            : test.questions;
    numbers.dataset.built = '';
    clearProgress();
    // --------------------------------------------------------
    // RESET TIMER
    // --------------------------------------------------------
    clearInterval(
        timerId
    );
    timer.classList.remove(
        'urgent'
    );
    // --------------------------------------------------------
    // SHOW EXAM
    // --------------------------------------------------------
    start.classList.add(
        'hidden'
    );
    exam.classList.remove(
        'hidden'
    );
    // --------------------------------------------------------
    // RENDER
    // --------------------------------------------------------
    render();
    // --------------------------------------------------------
    // SHOW TIMER
    // --------------------------------------------------------
    updateTimer();
    // --------------------------------------------------------
    // START TIMER
    // --------------------------------------------------------
    timerId =
        setInterval(
            tick,
            1000
        );
}
// ============================================================
// UPDATE TIMER
// ============================================================
function updateTimer() {
    if (seconds < 0) {
        seconds = 0;
    }
    timer.textContent =
        fmt(seconds);
    if (seconds <= 60) {
        timer.classList.add(
            'urgent'
        );
    }
}
// ============================================================
// TIMER TICK
// ============================================================
function tick() {
    if (finished) {
        return;
    }
    seconds--;
    updateTimer();
    // ----------------------------------------------------------
    // Persist progress every 10 seconds so a refresh or crash
    // loses at most a few seconds of state, without hammering
    // sessionStorage on every single tick.
    // ----------------------------------------------------------
    if (seconds % 10 === 0) {
        saveProgress();
    }
    if (seconds <= 0) {
        seconds = 0;
        updateTimer();
        clearInterval(
            timerId
        );
        finish(true);
    }
}
// ============================================================
// RENDER QUESTION
// ============================================================
//
// Rebuilds only the current question's markup. The number grid
// is built once (buildNumbers) and afterwards only has classes
// toggled in place, and option selection likewise only toggles
// classes rather than re-rendering — this avoids a full DOM
// rebuild of every question button on every click, which used
// to happen on both "select an option" and "go to question N"
// for every test, regardless of size.
// ============================================================
function render() {
    const q =
        questions[idx];
    if (!q) {
        return;
    }
    // --------------------------------------------------------
    // PROGRESS
    // --------------------------------------------------------
    progress.textContent =
        'Question ' +
        (idx + 1) +
        ' of ' +
        questions.length;
    updateAnsweredCount();
    // --------------------------------------------------------
    // QUESTION (option display order shuffled per attempt when
    // the teacher enabled shuffling — the underlying letter/
    // answer mapping is untouched, so scoring is unaffected)
    // --------------------------------------------------------
    let entries =
        Object.entries(
            q.options || {}
        );
    if (test.shuffle) {
        entries =
            shuffleArray(
                entries.slice()
            );
    }
    question.innerHTML =
        '<h2>' +
        esc(
            q.question
        ) +
        '</h2>' +
        entries
        .map(
            function ([key, value]) {
                const selected =
                    answers[q.id] === key
                        ? ' selected'
                        : '';
                return (
                    '<button ' +
                    'type="button" ' +
                    'class="option' +
                    selected +
                    '" ' +
                    'data-option="' +
                    esc(key) +
                    '">' +
                    '<b>' +
                    esc(key) +
                    ')</b> ' +
                    esc(value) +
                    '</button>'
                );
            }
        )
        .join('');
    // --------------------------------------------------------
    // MARK FOR REVIEW
    // --------------------------------------------------------
    markBtn.classList.toggle(
        'active',
        !!marked[q.id]
    );
    markBtn.onclick =
        function () {
            if (finished) {
                return;
            }
            marked[q.id] =
                !marked[q.id];
            markBtn.classList.toggle(
                'active',
                !!marked[q.id]
            );
            updateCurrentNumber();
            saveProgress();
        };
    // --------------------------------------------------------
    // PREVIOUS / NEXT
    // --------------------------------------------------------
    prevBtn.disabled =
        idx === 0;
    nextBtn.disabled =
        idx ===
        questions.length - 1;
    // --------------------------------------------------------
    // NUMBER GRID: build once, then only toggle classes
    // --------------------------------------------------------
    if (!numbers.dataset.built) {
        buildNumbers();
    }
    updateCurrentNumber();
}
// ============================================================
// UPDATE ANSWERED COUNT
// ============================================================
function updateAnsweredCount() {
    answeredCount.textContent =
        Object.keys(
            answers
        ).length +
        ' answered';
}
// ============================================================
// BUILD NUMBER GRID (once per test attempt)
// ============================================================
function buildNumbers() {
    numbers.innerHTML =
        questions
            .map(
                function (item, n) {
                    return (
                        '<button ' +
                        'type="button" ' +
                        'class="qnum" ' +
                        'data-n="' +
                        n +
                        '">' +
                        (n + 1) +
                        '</button>'
                    );
                }
            )
            .join('');
    numbers.dataset.built = '1';
}
// ============================================================
// UPDATE "CURRENT" HIGHLIGHT ON NUMBER GRID
// ============================================================
function updateCurrentNumber() {
    numbers
        .querySelectorAll('.qnum')
        .forEach(function (button, n) {
            button.classList.toggle(
                'current',
                n === idx
            );
            button.classList.toggle(
                'answered',
                !!answers[questions[n].id]
            );
            button.classList.toggle(
                'marked',
                !!marked[questions[n].id]
            );
        });
}
// ============================================================
// DELEGATED CLICK HANDLERS (attached once)
// ============================================================
question.addEventListener(
    'click',
    function (event) {
        if (finished) {
            return;
        }
        const button =
            event.target.closest('.option');
        if (!button) {
            return;
        }
        const q =
            questions[idx];
        answers[q.id] =
            button.dataset.option;
        // Toggle selection without re-rendering the whole question
        question
            .querySelectorAll('.option')
            .forEach(function (b) {
                b.classList.toggle(
                    'selected',
                    b === button
                );
            });
        updateAnsweredCount();
        updateCurrentNumber();
        saveProgress();
    }
);
numbers.addEventListener(
    'click',
    function (event) {
        if (finished) {
            return;
        }
        const button =
            event.target.closest('.qnum');
        if (!button) {
            return;
        }
        idx = Number(button.dataset.n);
        render();
        saveProgress();
    }
);
// ============================================================
// PREVIOUS BUTTON
// ============================================================
prevBtn.onclick =
    function () {
        if (
            !finished &&
            idx > 0
        ) {
            idx--;
            render();
            saveProgress();
        }
    };
// ============================================================
// NEXT BUTTON
// ============================================================
nextBtn.onclick =
    function () {
        if (
            !finished &&
            idx <
            questions.length - 1
        ) {
            idx++;
            render();
            saveProgress();
        }
    };
// ============================================================
// SUBMIT BUTTON
// ============================================================
submitBtn.onclick =
    function () {
        finish(false);
    };
// ============================================================
// FINISH TEST
// ============================================================
function finish(auto) {
    // --------------------------------------------------------
    // PREVENT DOUBLE SUBMISSION
    // --------------------------------------------------------
    if (finished) {
        return;
    }
    // --------------------------------------------------------
    // SAFETY CHECK
    // --------------------------------------------------------
    if (
        !questions ||
        !Array.isArray(
            questions
        ) ||
        questions.length === 0
    ) {
        return;
    }
    // --------------------------------------------------------
    // MANUAL CONFIRMATION
    // --------------------------------------------------------
    if (!auto) {
        const unansweredNow =
            questions.length -
            Object.keys(answers).length;
        const confirmed =
            confirm(
                unansweredNow > 0
                    ? unansweredNow +
                      ' question(s) are still unanswered. Submit anyway?'
                    : 'Are you sure you want to submit the test?'
            );
        if (!confirmed) {
            return;
        }
    }
    // --------------------------------------------------------
    // MARK FINISHED
    // --------------------------------------------------------
    finished = true;
    // --------------------------------------------------------
    // STOP TIMER
    // --------------------------------------------------------
    clearInterval(
        timerId
    );
    // --------------------------------------------------------
    // CORRECT
    // --------------------------------------------------------
    let correct = 0;
    questions.forEach(
        function (q) {
            if (
                answers[q.id] ===
                q.answer
            ) {
                correct++;
            }
        }
    );
    // --------------------------------------------------------
    // ATTEMPTED
    // --------------------------------------------------------
    const attempted =
        Object.keys(
            answers
        ).length;
    // --------------------------------------------------------
    // WRONG
    // --------------------------------------------------------
    let wrong = 0;
    Object.keys(
        answers
    ).forEach(
        function (id) {
            const q =
                questions.find(
                    function (item) {
                        return (
                            String(
                                item.id
                            ) ===
                            String(id)
                        );
                    }
                );
            if (
                q &&
                answers[id] !==
                q.answer
            ) {
                wrong++;
            }
        }
    );
    // --------------------------------------------------------
    // UNANSWERED
    // --------------------------------------------------------
    const unanswered =
        Math.max(
            0,
            questions.length -
            attempted
        );
    // --------------------------------------------------------
    // NEGATIVE MARKING
    // --------------------------------------------------------
    const negativeMarking =
        Number(test.negativeMarking) || 0;
    const rawScore =
        Math.round(
            (
                correct -
                wrong * negativeMarking
            ) * 100
        ) / 100;
    // --------------------------------------------------------
    // PERCENTAGE (based on raw score, so negative marking is
    // reflected — can go below 0 if wrong answers outweigh
    // correct ones)
    // --------------------------------------------------------
    const percent =
        questions.length > 0
            ? Math.round(
                (
                    rawScore /
                    questions.length
                ) * 100
            )
            : 0;
    // --------------------------------------------------------
    // TIME TAKEN
    // --------------------------------------------------------
    const timeTaken =
        Math.max(
            0,
            Math.round(
                (
                    Date.now() -
                    startTime
                ) / 1000
            )
        );
    // --------------------------------------------------------
    // MARKED FOR REVIEW (ids)
    // --------------------------------------------------------
    const markedIds =
        Object.keys(marked)
            .filter(
                function (id) {
                    return marked[id];
                }
            );
    // --------------------------------------------------------
    // RESULT
    // --------------------------------------------------------
    const result = {
        title:
            test.title || 'Mock Test',
        name:
            studentName,
        roll:
            rollNo,
        total:
            questions.length,
        attempted:
            attempted,
        correct:
            correct,
        wrong:
            wrong,
        unanswered:
            unanswered,
        negativeMarking:
            negativeMarking,
        rawScore:
            rawScore,
        percent:
            percent,
        timeTaken:
            timeTaken,
        answers:
            answers,
        marked:
            markedIds,
        questions:
            questions,
        autoSubmitted:
            auto
    };
    // --------------------------------------------------------
    // SAVE RESULT
    // --------------------------------------------------------
    try {
        sessionStorage.setItem(
            'mockResult',
            JSON.stringify(
                result
            )
        );
    } catch (error) {
        console.error(
            'Result save error:',
            error
        );
        alert(
            'Unable to save your result.'
        );
        finished = false;
        return;
    }
    // --------------------------------------------------------
    // CLEAR IN-PROGRESS STATE — the attempt is done
    // --------------------------------------------------------
    clearProgress();
    // --------------------------------------------------------
    // RESULT PAGE
    // --------------------------------------------------------
    window.location.href =
        'result.html';
}
